from __future__ import annotations

from pathlib import Path
import numpy as np
import pandas as pd

from .data_audit import EVENT_COLUMNS
from .utils import dump_json


def generate(folder, seed=17, groups=48, accounts_per_group=12, target=False):
    """Mechanistic fixture only: never named or treated as a real benchmark."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    accounts, events, edges = [], [], []
    prefix = "synthetic_target" if target else "synthetic_source"
    epoch = pd.Timestamp("2020-01-01", tz="UTC")
    for g in range(groups):
        group_id = f"{prefix}_g{g:03}"
        base = epoch + pd.Timedelta(days=g * 9)
        offset = rng.normal(0, .8)
        labels = rng.permutation(np.tile([0, 1], accounts_per_group // 2 + 1)[:accounts_per_group])
        shared_times = np.sort(rng.uniform(0, 6 * 86400, 20))
        benign_sync = g % 6 == 0
        for u in range(accounts_per_group):
            uid = f"{prefix}_{g:03}_{u:03}"
            label = int(labels[u])
            mean = 5.2 + offset - label * (.6 if not target else .15)
            prediction = base + pd.Timedelta(days=7)
            accounts.append(dict(account_id=uid, label=label, group_id=group_id, followers=int(rng.lognormal(mean, 1.1)), following=int(rng.lognormal(5.3 + label * .3, .8)), statuses=int(rng.lognormal(7 + label * .3, .8)), listed=int(rng.lognormal(1.5, .8)), verified=int(rng.random() < .04), default_profile=int(rng.random() < .2 + label * .15), description_length=int(rng.integers(0, 160)), prediction_at=prediction, profile_observed_at=prediction, benign_synchronization=bool(benign_sync and label == 0)))
            count = int(rng.integers(15, 30))
            for j in range(count):
                coordinated = (label == 1 and j < 20) or (benign_sync and label == 0 and j < 8)
                if coordinated:
                    seconds = shared_times[j] + rng.normal(0, 8 if not target else 65)
                    oid = f"{group_id}_object_{j}"
                else:
                    seconds = rng.uniform(0, 6 * 86400)
                    oid = f"{group_id}_object_{rng.integers(0, 35)}"
                events.append(dict(event_id=f"e{len(events)}", account_id=uid, timestamp=base + pd.Timedelta(seconds=float(max(0, seconds))), object_id=oid, action="post"))
            if u:
                edges.append(dict(source=uid, target=f"{prefix}_{g:03}_{u-1:03}", relation="follows"))
    pd.DataFrame(accounts).to_csv(folder / "accounts.csv", index=False)
    pd.DataFrame(events, columns=EVENT_COLUMNS).to_csv(folder / "events.csv", index=False)
    pd.DataFrame(edges).to_csv(folder / "edges.csv", index=False)
    dump_json(folder / "metadata.json", dict(name=prefix, data_kind="synthetic", group_type="synthetic", chronology_supported=True,
        source="Locally generated mechanistic fixture", license="CC0 fixture generated by this project", seed=seed,
        limitations="Synthetic group structure, class effects, synchronization and target shift are designed assumptions. Not evidence about Twitter or real campaigns."))
